const dictionaries: Record<Language, Record<TranslationKey, string>> = {
  'en-US': enUS,
  'pt-BR': ptBR,
}

type TranslationParams = Record<string, string | number>
type Translate = (key: TranslationKey, params?: TranslationParams) => string

// Context modules intentionally expose this pure helper for unit tests.
// eslint-disable-next-line react-refresh/only-export-components
export function translate(language: Language, key: TranslationKey, params: TranslationParams = {}): string {
  return Object.entries(params).reduce(
    (message, [name, value]) => message.replaceAll(`{${name}}`, String(value)),
    dictionaries[language][key],
  )
}

interface I18nValue {
  language: Language
  setLanguage: (language: Language) => void
  t: Translate
}

const I18nContext = createContext<I18nValue | null>(null)
const STORAGE_KEY = 'nemesys_language'

function initialLanguage(): Language {
  if (typeof window === 'undefined') return 'pt-BR'
  const stored = window.localStorage.getItem(STORAGE_KEY)
  return stored === 'en-US' || stored === 'pt-BR' ? stored : 'pt-BR'
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<Language>(initialLanguage)

  const setLanguage = (nextLanguage: Language) => {
    window.localStorage.setItem(STORAGE_KEY, nextLanguage)
    setLanguageState(nextLanguage)
  }

  useEffect(() => {
    document.documentElement.lang = language
  }, [language])

  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, params) => translate(language, key, params),
  }), [language])

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>
}

// Context hooks and their provider share the same typed context by design.
// eslint-disable-next-line react-refresh/only-export-components
export function useI18n(): I18nValue {
  const value = useContext(I18nContext)
  if (!value) throw new Error('useI18n must be used inside I18nProvider')
  return value
}
